import { readFileSync, writeFileSync } from 'node:fs';
import { busRoutes } from '../src/lib/bus-routes';
import { matchRoutes } from '../src/lib/route-matching';
import { snapshotId } from '../src/lib/timetable';

const report = JSON.parse(readFileSync('data/timetable/reconciliation.json', 'utf8'));
const legacy: { from: string; to: string }[] = JSON.parse(readFileSync('data/timetable/review/legacy-routes.json', 'utf8'));
const pairs = [...new Map(legacy.filter(route => route.from.trim() && route.to.trim()).map(route => [JSON.stringify([route.from, route.to]), { from: route.from, to: route.to }])).values()];
const disappeared = pairs.filter(pair => matchRoutes(pair.from, pair.to).length === 0).map(pair => ({ ...pair,
  reason: /closed/i.test(pair.to) ? 'Original PDF marks this service temporarily closed; retained for review.' :
    pair.to === '152D' ? 'Previous data swapped To and Via. 152D is a road label, not a destination; the published endpoint is used.' :
    pair.to === 'M/G' ? 'Previous data swapped To and Via. Charkhi Dadri.pdf page 8 prints destination Narnaul, via M/G. The abbreviation is retained for review.' : 'Requires source review.',
}));
const coverage = { snapshotId, previousServices: legacy.length, previousRouteLabels: pairs.length, disappeared,
  acceptance: [
    { from: 'Delhi', to: 'Ludhiana' }, { from: 'Bhiwani', to: 'Delhi' }, { from: 'Bhiwani', to: 'Rohtak' },
  ].map(pair => ({ ...pair, services: matchRoutes(pair.from, pair.to).length,
    viaMatches: matchRoutes(pair.from, pair.to).filter(route => route.matchedVia).length })) };
writeFileSync('data/timetable/legacy-coverage.json', JSON.stringify(coverage, null, 2) + '\n');
const unresolved = report.unresolvedRows.map(row => `| ${row.id} | ${row.sourcePdf}${row.pdfRef ? ` p.${row.pdfRef.page}` : ''} | ${row.reasons.join('; ')} |`).join('\n');
const table = report.files.map(file => `| ${file.csv} | ${file.input} | ${file.imported ?? 0} | ${file.confirmedDuplicates} | ${file.review ?? 0} |`).join('\n');
const text = `# Timetable reconciliation

Snapshot: \`${snapshotId}\`. This report is generated by \`npm run timetable:import\`.

All **${report.inputRows.toLocaleString('en-IN')} CSV input rows** are retained in \`audit.json\`, including every raw field, ordered raw values, CSV record number, source PDF and verified PDF page/table/row. Record numbers start at 1 after the header and count CSV records, including records containing quoted newlines.

**${busRoutes.length.toLocaleString('en-IN')} searchable services; ${report.unresolvedRows.length} rows held for review; ${report.confirmedDuplicateServices} confirmed duplicate services merged; ${report.recoveredServices} additional PDF services recovered.**

## Per-file input accounting

| CSV | Input | Imported | Linked duplicate | Review |
| --- | ---: | ---: | ---: | ---: |
${table}

## Rows held for review

| Record | Evidence | Reason |
| --- | --- | --- |
${unresolved}

## PDF and repetition checks

All 25 original PDFs and ${report.pdfs.reduce((sum, pdf) => sum + pdf.pages, 0)} pages were extracted. PDF hashes and parsed row counts are in \`reconciliation.json\`; original geometric cells, page text and cell bounds remain in \`pdf-extracts/\`. There are ${report.unparsedPdfRows.length} service rows with an unestablished PDF column schema, and ${report.pdfRecoveryCandidates.length} unmatched PDF service candidates after reconciliation. No additional services were recovered beyond the CSV inputs in this snapshot.

There are ${report.repeatedServiceGroups} groups of identical service descriptions. These remain separate observations with their own source references in \`review/repeated-service-candidates.json\`. Matching route/time/operator values alone do not prove they are the same service. No unconfirmed service duplicates are merged.

${report.viaReview.length} records have a via parsing review note in \`reconciliation.json#viaReview\`. Their verified endpoints and departure remain searchable; ambiguous tokens are withheld as intermediate destinations. Reviewed unambiguous segments (for example Rohtak in Rohtak-Bhi) remain searchable.

## Existing route coverage

Compared ${legacy.length} previous services across ${pairs.length} existing route labels using the shared matcher. **${disappeared.length} existing searchable origin/destination labels would disappear.** Details: \`legacy-coverage.json\`.
${disappeared.map(pair => `- ${pair.from} → ${pair.to}: ${pair.reason}`).join('\n')}

## Acceptance route counts

${coverage.acceptance.map(pair => `- ${pair.from} → ${pair.to}: ${pair.services} services, including ${pair.viaMatches} intermediate-destination matches.`).join('\n')}

Counts describe this downloaded source snapshot, not live operations. See \`REVIEW.md\` for the reviewed source conventions, exceptions and regeneration commands.
`;
writeFileSync('data/timetable/RECONCILIATION.md', text);
console.log(JSON.stringify(coverage, null, 2));
